"""Derive ``bitrep_trusted_objects.py`` from a known-good BitRep clone at the pinned commit (reproducible).

Usage: ``python derive_bitrep_trusted_objects.py <known-good-bitrep-clone> <commit-id> [--write]``

The commit object is hashed in-process against ``<commit-id>``, its tree id is read from the verified bytes, every tree
and blob below it is re-hashed in-process, and the module text is printed (or written next to this script with
``--write``). Run it only against a clone you trust to hold the genuine pinned commit; review the diff.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _checkout():
    spec = importlib.util.spec_from_file_location("bitrep_checkout", HERE / "bitrep_checkout.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


HEADER = '''"""Trusted Git object identities of the pinned BitRep source (cognous-evidence-attestation).

SOURCE-AUTHENTICATION ANCHORS, NOT OPERATIONAL AUTHORITY: they say which exact bytes the verifier imports; they grant
nothing and are not a trust registry. They are independent of any checkout's refs, HEAD, tags, replace objects,
alternates or object database, which may only supply bytes that hash to these ids.

Generated by ``derive_bitrep_trusted_objects.py``; change them only together with ``PIN`` in ``bitrep_adapter.py``
(see CHANGELOG, "How to update the BitRep pin"). Do not edit by hand.
"""

'''


def render(root: Path, commit: str) -> str:
    checkout = _checkout()
    tree = checkout.verify_commit(Path(root), commit)
    entries = checkout.verified_tree_entries(Path(root), tree)
    anchors = checkout.TrustedObjects(commit, tree, tuple(entries))
    checkout.verify_anchored(Path(root), anchors)
    lines = [HEADER, f'COMMIT = "{commit}"\n', f'TREE = "{tree}"\n\n', "FILES = (\n"]
    lines += [f'    ("{mode}", "{rel}", "{blob}"),\n' for mode, rel, blob in entries]
    lines.append(")\n")
    return "".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__)
        return 2
    text = render(Path(argv[0]), argv[1])
    if "--write" in argv[2:]:
        (HERE / "bitrep_trusted_objects.py").write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
